[CmdletBinding()]
param(
    [Parameter(Mandatory)][string] $StlInclude,
    [string] $ProjectRoot = (Split-Path -Parent $PSScriptRoot),
    [string] $DependencyInclude,
    [string] $OutputDirectory,
    [switch] $IncludeTests
)

$ErrorActionPreference = 'Stop'
$ProjectRoot = [IO.Path]::GetFullPath($ProjectRoot)
$StlInclude = [IO.Path]::GetFullPath($StlInclude)
if (!$DependencyInclude) {
    $DependencyInclude = Join-Path $ProjectRoot 'build/windows-x64/vcpkg_installed/x64-windows-static/include'
}
if (!$OutputDirectory) { $OutputDirectory = Join-Path $ProjectRoot 'include/launcher' }
$DependencyInclude = [IO.Path]::GetFullPath($DependencyInclude)
$OutputDirectory = [IO.Path]::GetFullPath($OutputDirectory)

$metadata = [IO.File]::ReadAllText((Join-Path $StlInclude 'yvals_core.h'))
$stlVersion = [regex]::Match($metadata, '(?m)^#define\s+_MSVC_STL_VERSION\s+(\d+)').Groups[1].Value
$stlUpdate = [regex]::Match($metadata, '(?m)^#define\s+_MSVC_STL_UPDATE\s+(\d+L)').Groups[1].Value
if (!$stlVersion -or !$stlUpdate) { throw 'Cannot identify the selected MSVC STL.' }

$roots = @(Join-Path $ProjectRoot 'include'; $DependencyInclude)
$pending = [Collections.Generic.Queue[string]]::new()
foreach ($directory in @('src', 'include') + $(if ($IncludeTests) { @('tests') } else { @() })) {
    Get-ChildItem -LiteralPath (Join-Path $ProjectRoot $directory) -Recurse -File |
        Where-Object { $_.Extension -in '.cpp', '.hpp', '.h', '.hh' -and
            $_.Name -notin 'seenthemall.hh', 'std_header_macros.hh' } |
        ForEach-Object { $pending.Enqueue($_.FullName) }
}
$visited = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
$headers = [Collections.Generic.SortedSet[string]]::new([StringComparer]::Ordinal)
$includePattern = [regex]::new('(?m)^\s*#\s*include\s*[<"]([^>"\r\n]+)[>"]')
$cWrappers = @('cassert', 'cctype', 'cerrno', 'cfenv', 'cfloat', 'cinttypes',
    'ciso646', 'climits', 'clocale', 'cmath', 'csetjmp', 'csignal', 'cstdalign',
    'cstdarg', 'cstdbool', 'cstddef', 'cstdint', 'cstdio', 'cstdlib', 'cstring',
    'ctgmath', 'ctime', 'cuchar', 'cwchar', 'cwctype')
$publicHeaders = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
$standardModule = Join-Path ([IO.Path]::GetDirectoryName($StlInclude)) 'modules/std.ixx'
foreach ($match in $includePattern.Matches([IO.File]::ReadAllText($standardModule))) {
    $name = $match.Groups[1].Value
    if ($name -notmatch '[/\\.]' -and !$name.StartsWith('_')) { [void]$publicHeaders.Add($name) }
}
foreach ($name in $cWrappers) { [void]$publicHeaders.Add($name) }
while ($pending.Count) {
    $file = $pending.Dequeue()
    if (!$visited.Add($file)) { continue }
    foreach ($match in $includePattern.Matches([IO.File]::ReadAllText($file))) {
        $name = $match.Groups[1].Value
        # Importing sources include these generated files. They are outputs,
        # not evidence of which real headers the source/dependencies need.
        if ([IO.Path]::GetFileName($name) -in 'seenthemall.hh', 'std_header_macros.hh') { continue }
        # The module's public header inventory excludes internal x* headers.
        # Do not invent guards for internal STL, UCRT or SDK declarations.
        if ($publicHeaders.Contains($name) -and (Test-Path -LiteralPath (Join-Path $StlInclude $name))) {
            [void]$headers.Add($name)
            continue
        }
        foreach ($root in @([IO.Path]::GetDirectoryName($file)) + $roots) {
            $candidate = Join-Path $root $name
            if (Test-Path -LiteralPath $candidate -PathType Leaf) {
                $pending.Enqueue([IO.Path]::GetFullPath($candidate))
                break
            }
        }
    }
}

$guards = [Collections.Generic.List[object]]::new()
$macroHeaders = [Collections.Generic.List[string]]::new()
$guardless = [Collections.Generic.List[string]]::new()
foreach ($name in $headers) {
    if ($name -in $cWrappers) {
        $macroHeaders.Add($name)
    }
    if ($name -eq 'version') { continue } # Its real macro interface stays live.
    $text = [IO.File]::ReadAllText((Join-Path $StlInclude $name))
    $guard = [regex]::Match($text, '(?m)^#ifndef\s+([A-Z_][A-Z_0-9]*)\s*\r?\n#define\s+\1(?:\s|$)')
    if (!$guard.Success) {
        $guardless.Add($name) # In particular, <cassert> intentionally re-evaluates NDEBUG.
        continue
    }
    $guards.Add([pscustomobject]@{ Header = $name; Guard = $guard.Groups[1].Value })
}

$preamble = @(
    '// Generated by tools/generate-seenthemall.ps1 from the selected MSVC headers.',
    '// MSVC compatibility adapter for Launcher''s import std build.',
    '// Regenerate and validate after changing the toolset or dependencies.',
    '#pragma once'
)
$prelude = @($preamble; ''; '// Include before import std; after the real SDK PCH boundary.';
    '// Real C wrappers retain macros, global CRT names and overload declarations.';
    '#include <version>')
foreach ($name in $macroHeaders) { $prelude += "#include <$name>" }

$shim = @($preamble; ''; '// Include after import std; and std_header_macros.hh.';
    '#include <version>';
    "#if !defined(_MSC_VER) || _MSVC_STL_VERSION != $stlVersion || _MSVC_STL_UPDATE != $stlUpdate";
    '#error Regenerate seenthemall.hh for this MSVC STL.';
    '#endif'; '';
    'static_assert(std::is_same_v<int, int>, "Import std before seenthemall.hh.");'; '')
foreach ($entry in $guards) {
    $shim += @("#ifndef $($entry.Guard)", "#define $($entry.Guard) // <$($entry.Header)>", '#endif')
}
if ($guardless.Count) { $shim += @('', ('// No fabricated guard: ' + ($guardless -join ', '))) }
[IO.Directory]::CreateDirectory($OutputDirectory) | Out-Null
$encoding = [Text.UTF8Encoding]::new($false)
# CMake reruns the scan when sources/dependencies change. Preserve timestamps
# when the actual adapter is unchanged so that scan does not rebuild consumers.
function Write-GeneratedHeader([string] $Name, [string] $Content) {
    $path = Join-Path $OutputDirectory $Name
    if (!(Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path) -cne $Content) {
        [IO.File]::WriteAllText($path, $Content, $encoding)
    }
}
Write-GeneratedHeader 'std_header_macros.hh' (($prelude -join "`n") + "`n")
Write-GeneratedHeader 'seenthemall.hh' (($shim -join "`n") + "`n")
"Generated $($guards.Count) public guards; retained $($macroHeaders.Count) real macro headers."
"Scanned $($visited.Count) local/dependency files. STL $stlVersion/$stlUpdate."
